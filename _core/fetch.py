#!/usr/bin/env python3
"""Fetch the StepFun doc corpus into corpus/, then rebuild corpus/_index.md.

Deterministic by design: no LLM, no guessing. Run it again
whenever the docs change; it re-downloads and rewrites the manifest, and never
touches anything outside corpus/.

Usage:
    python3 _core/fetch.py            # fetch all pages listed in llms.txt
    python3 _core/fetch.py --dry-run  # show what would be fetched, write nothing
"""
from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORPUS = ROOT / "corpus"
BASE = "https://platform.stepfun.ai/docs"
LLMS_URL = f"{BASE}/llms.txt"
MANIFEST = CORPUS / "_index.md"

# Doc-path prefix -> corpus subdirectory. Order matters: the first matching
# prefix wins, so more specific prefixes come first.
SECTION_MAP = {
    "en/step-plan/": "step-plan",
    "en/step-code/": "step-code",
    "en/api-reference/": "api-reference",
    "en/guides/": "guides",
    "en/quickstart/": "guides/quickstart",
}

# Human-readable section titles for the manifest.
SECTION_TITLE = {
    "step-plan": "Step Plan (subscription)",
    "step-code": "Step Code (agent CLI)",
    "api-reference": "API Reference",
    "guides": "Guides & Models",
    "misc": "Agreements, FAQ & misc",
}

LINK_RE = re.compile(r"^- \[(?P<title>[^\]]+)\]\((?P<url>https://platform\.stepfun\.ai/docs/(?P<path>en/[^)]+\.md))\)\s*$")


def classify(path: str) -> tuple[str, str]:
    """Return (corpus subdirectory, path relative to that subdirectory)."""
    for prefix, subdir in SECTION_MAP.items():
        if path.startswith(prefix):
            return subdir, path[len(prefix):]
    return "misc", path[len("en/"):]


def fetch(url: str) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "stepfun-docs-fetch/1.0"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read().decode("utf-8")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    try:
        index_text = fetch(LLMS_URL)
    except Exception as exc:  # noqa: BLE001 - report and fail closed
        print(f"ERROR: could not fetch {LLMS_URL}: {exc}", file=sys.stderr)
        return 1

    if not args.dry_run:
        CORPUS.mkdir(parents=True, exist_ok=True)
        (CORPUS / "llms.txt").write_text(index_text, encoding="utf-8")

    entries: list[tuple[str, str, str, str]] = []  # (subdir, relpath, path, title)
    for line in index_text.splitlines():
        m = LINK_RE.match(line.strip())
        if m:
            subdir, rel = classify(m.group("path"))
            entries.append((subdir, rel, m.group("path"), m.group("title")))

    ok, failed = 0, []
    for subdir, rel, path, title in entries:
        dest = CORPUS / subdir / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        if args.dry_run:
            print(f"[dry-run] {path} -> corpus/{subdir}/{rel}")
            continue
        try:
            dest.write_text(fetch(f"{BASE}/{path}"), encoding="utf-8")
            ok += 1
            print(f"  ok  {path}")
        except Exception as exc:  # noqa: BLE001
            failed.append((path, str(exc)))
            print(f"  FAIL {path}: {exc}", file=sys.stderr)

    if args.dry_run:
        print(f"\n{len(entries)} pages would be fetched into corpus/")
        return 0

    write_manifest(entries, failed)
    print(f"\nfetched {ok}/{len(entries)} pages into corpus/ -> {MANIFEST}")
    if failed:
        print(f"{len(failed)} FAILED — see manifest for status", file=sys.stderr)
    return 0 if not failed else 2


def write_manifest(entries: list[tuple[str, str, str, str]], failed: list[tuple[str, str]]) -> None:
    """Rewrite corpus/_index.md as the checkbox state machine."""
    now = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    failed_paths = {p for p, _ in failed}
    by_section: dict[str, list[tuple[str, str]]] = {}
    for subdir, rel, path, title in entries:
        by_section.setdefault(subdir, []).append((path, title, rel))

    lines = [
        "# Corpus Manifest — the state machine",
        "",
        "> Generated by `_core/fetch.py`. **Never hand-edit this file.**",
        f"> Last fetch: {now}",
        "",
        "Pipeline status is answered by scanning this file, not by asking anyone.",
        "",
        "## Totals",
        "",
        f"- Pages listed in llms.txt: **{len(entries)}**",
        f"- Fetched: **{len(entries) - len(failed)}**",
        f"- Failed: **{len(failed)}**",
        "",
    ]

    for subdir in ["step-plan", "step-code", "api-reference", "guides", "guides/quickstart", "misc"]:
        rows = by_section.get(subdir)
        if not rows:
            continue
        lines += [f"## {SECTION_TITLE.get(subdir.split('/')[0], subdir)} — `corpus/{subdir}/`", "",
                  "| Status | Page | File |", "| --- | --- | --- |"]
        for path, title, rel in rows:
            mark = "x" if path not in failed_paths else " "
            lines.append(f"| [{mark}] | {title} | [`{subdir}/{rel}`]({subdir}/{rel}) |")
        lines.append("")

    if failed:
        lines += ["## Failures", "", "| Page | Error |", "| --- | --- |"]
        lines += [f"| {p} | {e.splitlines()[0][:120]} |" for p, e in failed]
        lines.append("")

    MANIFEST.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    raise SystemExit(main())
